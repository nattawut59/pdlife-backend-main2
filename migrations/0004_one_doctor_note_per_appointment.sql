-- =====================================================================
-- 0004 — หนึ่งการมาตรวจ = หนึ่งบันทึกของแพทย์
-- =====================================================================
--
-- ทำไมต้องมีไฟล์นี้
-- ----------------
-- 0001_init_schema.sql สร้าง doctor_notes ไว้โดย **ไม่มี index เลยสักอัน** — ต่างจาก
-- clinic_assessments ที่ยังมี index ธรรมดาบน appointment_id ให้
--
--     CREATE TABLE pdlife.doctor_notes (
--       appointment_id UUID NOT NULL REFERENCES pdlife.appointments(id),
--       ...
--     );
--     -- ไม่มี CREATE INDEX ตามมา
--
-- ผลสองอย่าง
--
--   1. ทุกครั้งที่เปิดตารางนัด backend ต้องไล่อ่าน doctor_notes ทั้งตารางเพื่อตอบว่า
--      นัดไหนบันทึกแล้ว — ตอนนี้ไม่รู้สึกเพราะยังไม่มีข้อมูล แต่โตขึ้นทุกวันที่คลินิกเปิด
--
--   2. ฐานข้อมูลยอมให้มีบันทึกหลายใบของการมาตรวจครั้งเดียวกัน แพทย์ที่เปิดสองแท็บแล้ว
--      กดบันทึกทั้งคู่จะได้สองใบที่เนื้อหาต่างกัน โดยไม่มีอะไรบอกว่าใบไหนคือแผนการรักษาจริง
--
-- unique index แก้ทั้งสองข้อพร้อมกัน — ค้นได้เร็วเท่า index ธรรมดา และบังคับกฎไปด้วย
--
--
-- ทำไมเป็นกฎที่ถูกต้อง ไม่ใช่แค่แก้ขัด
-- -----------------------------------
-- บันทึกผลการตรวจเป็นของ "การมาตรวจครั้งนั้น" เหมือนฟอร์มคัดกรอง — คนเดียวกันมา 5 ครั้ง
-- ต้องได้ 5 ใบแยกกัน และแต่ละครั้งมีใบเดียว การแก้บันทึกคือแก้ใบเดิม ไม่ใช่เขียนใบใหม่ทับ
--
-- (แก้บันทึกได้เสมอ ไม่มีการล็อก — แพทย์นึกอะไรออกทีหลังแล้วเขียนเพิ่มเป็นเรื่องปกติ
--  ส่วนการเปลี่ยนแปลงถูกบันทึกไว้ใน audit_logs อยู่แล้ว)
--
--
-- ก่อนรัน
-- -------
-- ถ้ามีข้อมูลซ้ำอยู่ก่อน คำสั่งนี้จะล้มเหลวและไม่เปลี่ยนอะไรเลย (ปลอดภัย) ตรวจด้วย
--
--     SELECT appointment_id, count(*)
--     FROM pdlife.doctor_notes
--     GROUP BY appointment_id
--     HAVING count(*) > 1;
--
-- ถ้าได้ 0 แถว รันไฟล์นี้ได้เลย
--
--
-- ย้อนกลับ
-- --------
--     DROP INDEX pdlife.idx_doctor_notes_appointment;
-- =====================================================================

CREATE UNIQUE INDEX idx_doctor_notes_appointment
  ON pdlife.doctor_notes (appointment_id);
