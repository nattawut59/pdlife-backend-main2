-- ทำไมต้องมีไฟล์นี้
-- ----------------
-- 0001_init_schema.sql สร้าง appointments ไว้แบบนี้
--
--     doctor_id  UUID REFERENCES pdlife.users(id)
--     visit_time TIME
--     CREATE INDEX idx_appointments_window ON ... (patient_id, visit_date);
--                  ^^^^^ index ตาม patient_id เท่านั้น ไม่มีอะไรกันหมอถูกจองซ้ำเลย
--
-- แปลว่าฐานข้อมูลยอมให้สร้างนัดสองใบขึ้นไปให้หมอคนเดียวกัน วันเดียวกัน เวลาเดียวกันได้
-- เฉย ๆ ตอนนี้ไม่พังเพราะเจ้าหน้าที่เป็นคนคีย์เองและดูตารางหมอด้วยตาก่อนกดสร้างทุกครั้ง —
-- แต่วันที่เปิดให้ผู้ป่วยจองคิวเอง (ตาม docs/HANDOVER.md) จะพังทันที
--
-- กันในโค้ดอย่างเดียวไม่พอ เพราะการอ่านก่อนเขียนมีช่องว่างระหว่างสองคำสั่งเสมอ (สองคนกด
-- จองพร้อมกัน อ่านว่า "ว่าง" ทั้งคู่ แล้วต่างคนต่างสร้าง) ข้อบังคับต้องอยู่ที่ฐานข้อมูล
-- ซึ่งเป็นที่เดียวที่รับประกันได้ — เหตุผลเดียวกับ 0003_one_assessment_per_appointment.sql
--
--
-- โมเดล slot ที่เลือก (ไม่มีในเอกสารต้นทางเลย — เป็นการตัดสินใจของทีม ไม่ใช่สเปกที่มีอยู่แล้ว)
-- --------------------------------------------------------------------------------------
-- ช่วงเวลาตายตัวต่อหมอ 1 คน (ค่าเริ่มต้น 30 นาที ดู APPOINTMENT_SLOT_MINUTES ใน
-- src/config/constants.ts) หมอ 1 คนรับได้ 1 นัดต่อช่วงเวลา — ฝั่งแอปพลิเคชันเช็คว่า
-- visit_time ตรง slot boundary ก่อนส่งมาถึงตรงนี้อยู่แล้ว (isValidSlotTime ใน
-- src/schemas/appointmentSchema.ts) ไฟล์นี้เป็นแค่ด่านสุดท้ายที่รับประกันจริง
--
-- นัดที่ยังไม่ระบุ doctor_id หรือ visit_time (เช่น จองไว้ก่อนแล้วค่อยจัดหมอทีหลัง) ไม่ติด
-- constraint นี้เลย เพราะ Postgres unique index ไม่นับ NULL ว่าชนกัน — ถูกต้องอยู่แล้ว
-- นัดที่ยังไม่รู้ว่าจะเป็นของหมอคนไหน ไม่ควรไปกันสิทธิ์ช่วงเวลาของใคร
--
-- นัดที่ถูกยกเลิกแล้ว (status = cancelled) ไม่นับว่าจองช่วงเวลานั้นอยู่ — ใช้สถานะแทนการลบ
-- นัด (ตาม docs/HANDOVER.md ที่อธิบายว่าทำไมไม่มี DELETE) ช่วงเวลาที่ถูกปล่อยคืนจึงต้องว่าง
-- ให้จองใหม่ได้จริง ไม่ใช่ถูกล็อกค้างไว้ตลอดกาล
--
--
-- ก่อนรัน
-- -------
-- ถ้ามีข้อมูลซ้ำอยู่ก่อน คำสั่งนี้จะล้มเหลวและไม่เปลี่ยนอะไรเลย (ปลอดภัย) ให้ตรวจด้วย
--
--     SELECT doctor_id, visit_date, visit_time, count(*)
--     FROM pdlife.appointments
--     WHERE status != 'cancelled' AND doctor_id IS NOT NULL AND visit_time IS NOT NULL
--     GROUP BY doctor_id, visit_date, visit_time
--     HAVING count(*) > 1;
--
-- ถ้าได้ 0 แถว รันไฟล์นี้ได้เลย ถ้ามีแถวซ้ำ ต้องคุยกับเจ้าหน้าที่ว่านัดคู่ไหนควรย้ายเวลา/หมอ
-- ก่อน ห้ามลบทิ้งเองโดยไม่ถาม
--
--
-- ย้อนกลับ
-- --------
--     DROP INDEX pdlife.idx_appointments_one_per_doctor_slot;
-- =====================================================================

CREATE UNIQUE INDEX idx_appointments_one_per_doctor_slot
  ON pdlife.appointments (doctor_id, visit_date, visit_time)
  WHERE status != 'cancelled' AND doctor_id IS NOT NULL AND visit_time IS NOT NULL;
