-- =====================================================================
-- 0003 — หนึ่งการมาตรวจ = หนึ่งฟอร์มคัดกรอง
-- =====================================================================
--
-- ทำไมต้องมีไฟล์นี้
-- ----------------
-- 0001_init_schema.sql สร้าง clinic_assessments ไว้แบบนี้
--
--     appointment_id UUID NOT NULL REFERENCES pdlife.appointments(id)
--     CREATE INDEX idx_assessments_appointment ON ... (appointment_id);
--                  ^^^^^ index ธรรมดา ไม่ใช่ unique
--
-- แปลว่าฐานข้อมูลยอมให้มีฟอร์มคัดกรองหลายใบของการมาตรวจครั้งเดียวกัน ซึ่งเกิดขึ้นได้จริง
-- เมื่อพยาบาลสองคนเปิดฟอร์มของผู้ป่วยคนเดียวกันพร้อมกันแล้วกดบันทึกไล่ ๆ กัน
--
-- ผลคือแพทย์เปิดมาเห็นสองใบที่ตอบไม่ตรงกัน โดยไม่มีอะไรบอกว่าใบไหนคือของจริง — และโค้ด
-- ฝั่ง service ก็ตัดสินใจแทนไม่ได้ ได้แต่เดาว่า "เอาใบที่ส่งล่าสุด" ซึ่งอาจไม่ใช่ใบที่ถูก
--
-- กันในโค้ดอย่างเดียวไม่พอ เพราะการอ่านก่อนเขียนมีช่องว่างระหว่างสองคำสั่งเสมอ
-- (อ่านว่า "ยังไม่มี" พร้อมกันทั้งคู่ แล้วต่างคนต่างเขียน) ข้อบังคับต้องอยู่ที่ฐานข้อมูล
-- ซึ่งเป็นที่เดียวที่รับประกันได้
--
--
-- ทำไมเป็นกฎที่ถูกต้อง ไม่ใช่แค่แก้ขัด
-- -----------------------------------
-- ฟอร์มคัดกรองเป็นของ "การมาตรวจครั้งนั้น" ไม่ใช่ของตัวผู้ป่วย — คนเดียวกันมา 5 ครั้ง
-- ต้องได้ 5 ใบแยกกัน และแต่ละครั้งต้องมีใบเดียว นี่คือสิ่งที่ฟอร์มกระดาษเป็นอยู่แล้ว
--
--
-- ก่อนรัน
-- -------
-- ถ้ามีข้อมูลซ้ำอยู่ก่อน คำสั่งนี้จะล้มเหลวและไม่เปลี่ยนอะไรเลย (ปลอดภัย) ให้ตรวจด้วย
--
--     SELECT appointment_id, count(*)
--     FROM pdlife.clinic_assessments
--     GROUP BY appointment_id
--     HAVING count(*) > 1;
--
-- ถ้าได้ 0 แถว รันไฟล์นี้ได้เลย
--
--
-- ย้อนกลับ
-- --------
--     DROP INDEX pdlife.idx_assessments_appointment;
--     CREATE INDEX idx_assessments_appointment
--       ON pdlife.clinic_assessments (appointment_id);
-- =====================================================================

-- index เดิมไม่ต้องมีแล้ว — unique index ค้นได้เร็วเท่ากันและทำหน้าที่แทนได้ทั้งหมด
-- เก็บทั้งสองอันไว้จะเป็นการเก็บ index ซ้ำซ้อนที่ต้องอัปเดตทุกครั้งที่เขียนโดยเปล่าประโยชน์
DROP INDEX IF EXISTS pdlife.idx_assessments_appointment;

CREATE UNIQUE INDEX idx_assessments_appointment
  ON pdlife.clinic_assessments (appointment_id);
